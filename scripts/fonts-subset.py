#!/usr/bin/env python3
"""Make the small editor fonts in templates/html/fonts/ from the full brand fonts (brand/fonts/, untouched).

Only the copy-review editor uses these; the design build keeps the full fonts.
Coverage: Basic Latin, Latin-1, Latin Extended-A, general punctuation (dashes, curly quotes,
ellipsis, bullet), plus a few symbols. Manrope keeps only the weights the editor renders (300-700).
Run:  pip install fonttools brotli && python3 scripts/fonts-subset.py
"""
import json, os
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer
from fontTools import subset

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'templates/html/fonts')
RANGES = [(0x20, 0x7E), (0xA0, 0x17F), (0x2010, 0x2027), (0x2030, 0x203A), (0x2190, 0x2193)]
EXTRA = [0x20AC, 0x2122, 0x2212, 0x2318, 0x2713, 0x2717, 0x26A0]
WANT = sorted({c for a, b in RANGES for c in range(a, b + 1)} | set(EXTRA))

def make(src, dst, wght=None):
    font = TTFont(os.path.join(ROOT, 'brand/fonts', src))
    have = set(font.getBestCmap())
    keep = [c for c in WANT if c in have]
    opts = subset.Options(); opts.flavor = 'woff2'; opts.layout_features = ['*']; opts.name_IDs = ['*']; opts.notdef_outline = True; opts.hinting = False
    sub = subset.Subsetter(opts); sub.populate(unicodes=keep); sub.subset(font)
    if wght: font = instancer.instantiateVariableFont(font, {'wght': wght})
    font.flavor = 'woff2'; font.save(os.path.join(OUT, dst))
    return keep, sorted(have)

os.makedirs(OUT, exist_ok=True)
res = {'Manrope': make('Manrope.ttf', 'Manrope-editor.woff2', (300, 700)), 'IBM Plex Mono': make('IBMPlexMono-Regular.ttf', 'IBMPlexMono-editor.woff2')}
cover = {k: v[0] for k, v in res.items()}
# Characters the FULL Manrope draws but the subset drops: if a post uses one, the editor falls back to the full fonts.
dropped = ''.join(chr(c) for c in res['Manrope'][1] if c >= 0x20 and c not in set(res['Manrope'][0]))
json.dump({'note': 'Generated by scripts/fonts-subset.py from brand/fonts. Copy-review editor only.', 'weights': {'Manrope': '300 700', 'IBM Plex Mono': '400'},
           'files': {'Manrope': 'Manrope-editor.woff2', 'IBM Plex Mono': 'IBMPlexMono-editor.woff2'},
           'unicodes': {k: ''.join(chr(c) for c in v) for k, v in cover.items()}, 'droppedFromManrope': dropped}, open(os.path.join(OUT, 'coverage.json'), 'w'), ensure_ascii=False, indent=1)
